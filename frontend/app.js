async function init(){
  // Sync the toggle's label to whatever theme the browser is actually
  // rendering (system preference) before the user has clicked it at all.
  isLight = !!(window.matchMedia && window.matchMedia('(prefers-color-scheme: light)').matches);
  $('themeBtn').textContent = isLight ? '☀️ Light' : '🌙 Dark';

  const res = await fetch('data.json');
  DATA = await res.json();
  currentProductId = DATA.products.find(p => p.id === 'ip17pro') ? 'ip17pro' : DATA.products[0].id;
  selectedVariant = defaultVariantSelection(getProduct(currentProductId));
  countries = JSON.parse(JSON.stringify(DATA.countries));
  initCompareState();
  tradeInAvailability = JSON.parse(JSON.stringify(DATA.trade_in_availability));
  tradeInDeviceId = DATA.trade_in_devices[DATA.trade_in_devices.length - 5].id; // a recent-ish model by default

  populateProductSelect();
  renderVariantFields();
  populateCurrencySelects();
  populateShipSelects();
  populateTradeInSelects();
  renderAssumptions();
  wireEvents();
  wireTabs();
  await Promise.all([initMap(), initWorldMap()]);
  renderAll();
}
init();
