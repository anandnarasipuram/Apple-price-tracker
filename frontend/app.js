function renderVariantFields(){
  const product = getProduct(currentProductId);
  const wrap = $('variantFields');
  const dims = Object.keys(product.variants || {});
  if (dims.length === 0){ wrap.innerHTML = ''; return; }
  wrap.innerHTML = dims.map(dim => {
    const opts = product.variants[dim];
    const label = dim.charAt(0).toUpperCase() + dim.slice(1);
    return `
      <div class="f-field">
        <label class="f-label" for="v-${dim}">${label}</label>
        <select id="v-${dim}" data-dim="${dim}" class="variant-select">
          ${opts.map(o => `<option value="${o.id}" ${selectedVariant[dim]===o.id?'selected':''}>${o.label}${o.delta?' (+$'+o.delta+')':''}</option>`).join('')}
        </select>
      </div>`;
  }).join('');
  wrap.querySelectorAll('.variant-select').forEach(s => {
    s.addEventListener('change', e => { selectedVariant[e.target.dataset.dim] = e.target.value; renderAll(); });
  });
}

