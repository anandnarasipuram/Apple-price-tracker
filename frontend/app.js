// Topology feature ids are zero-padded FIPS strings (e.g. "06" for California) —
// normalize with parseInt before looking them up.
function fipsToState(id){ return FIPS_TO_STATE[parseInt(id, 10)] || null; }

function stateCodeFromEvent(e){
  return fipsToState(e.target.getAttribute('data-fips'));
}

function updateMapColors(){
  if (!svgSel) return;
  const rows = allStateRows();
  const byCode = Object.fromEntries(rows.map(r => [r.code, r]));
  const { scale, min, max } = makeColorScale(rows);
  window.__currentRows = rows;
  window.__currentByCode = byCode;
  window.__currentScale = scale;

  svgSel.selectAll('path.state')
    .classed('no-data', d => !byCode[fipsToState(d.id)])
    .classed('pinned', d => pinnedState === fipsToState(d.id))
    .attr('fill', d => {
      const row = byCode[fipsToState(d.id)];
      return row ? scale(row.total_price) : '#555';
    })
    .attr('aria-label', d => {
      const row = byCode[fipsToState(d.id)];
      return row ? `${row.name}: ${fmtUsd(row.total_price)} total` : '';
    });

  $('legendMin').textContent = fmtUsd(min);
  $('legendMax').textContent = fmtUsd(max);
}

function onStateHover(e){
  const code = stateCodeFromEvent(e);
  const row = window.__currentByCode && window.__currentByCode[code];
  // A no-data feature (e.g. a US territory outside the 50 states) still needs
  // to clear whatever tooltip a previous hover left on screen.
  if (!row){ onStateLeave(e); return; }
  e.target.classList.add('hovered');
  const tt = $('tooltip');
  tt.hidden = false;
  tt.innerHTML = `
    <div class="tt-state">${row.name}</div>
    <div class="tt-spec">${productSpecLine(getProduct(currentProductId))}</div>
    <div class="tt-row"><span>Price before tax</span><span class="v">${fmtUsd2(row.base_price)}</span></div>
    <div class="tt-row"><span>Tax (${row.tax_rate_pct.toFixed(2)}%)</span><span class="v">${fmtUsd2(row.tax_amount)}</span></div>
    <div class="tt-row total"><span>Total price</span><span class="v">${fmtUsd2(row.total_price)}</span></div>
  `;
  const stage = $('mapStage');
  const stageBox = stage.getBoundingClientRect();
  let x, y;
  if (e.clientX !== undefined && e.type === 'pointermove'){
    x = e.clientX - stageBox.left;
    y = e.clientY - stageBox.top;
  } else {
    const box = e.target.getBoundingClientRect();
    x = box.left + box.width/2 - stageBox.left;
    y = box.top - stageBox.top;
  }
  positionTooltipClamped(tt, x, y);
}
function onStateLeave(e){
  e.target.classList.remove('hovered');
  $('tooltip').hidden = true;
}
function onStateClick(e){
  const code = stateCodeFromEvent(e);
  if (!code) return;
  pinnedState = pinnedState === code ? null : code;
  updateMapColors();
}

