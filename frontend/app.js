/* ===================================================================
   Apple Price Map — app.js
   Loads data.json (generated by apple_price_data.py), draws a USA
   choropleth (D3 + topojson, Albers USA projection) coloured by total
   price (list price + state sales tax), and keeps a sidebar + an
   always-available data table in sync with the same filters.
   =================================================================== */

const TOPOJSON_URL = 'https://cdn.jsdelivr.net/npm/us-atlas@3/states-10m.json';

