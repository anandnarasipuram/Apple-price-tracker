// Table view (accessible, always-available alternative to the map)
// ------------------------------------------------------------------
function renderTable(rows){
  const cheapest = Math.min(...rows.map(r => r.total_price));
  const sorted = rows.slice().sort((a,b) => {
    const dir = sortDir === 'asc' ? 1 : -1;
    if (typeof a[sortKey] === 'string') return a[sortKey].localeCompare(b[sortKey]) * dir;
    return (a[sortKey] - b[sortKey]) * dir;
  });
  $('stateTableBody').innerHTML = sorted.map(r => {
    const isBest = r.total_price === cheapest;
    const diff = r.total_price - cheapest;
    return `
      <tr class="${isBest ? 'best' : ''}">
        <td>${r.name}</td>
        <td class="num-col">${r.tax_rate_pct.toFixed(2)}%</td>
        <td class="num-col">${fmtUsd2(r.base_price)}</td>
        <td class="num-col">${fmtUsd2(r.tax_amount)}</td>
        <td class="num-col">${fmtUsd2(r.total_price)}</td>
        <td class="num-col">${isBest ? '—' : '+' + fmtUsd2(diff)}</td>
      </tr>`;
  }).join('');
}

